CATS = list(JOBS)
CATW = [14, 14, 14, 10, 7, 8, 7, 8, 5]
DUTY = ["负责日常工作的计划、执行与复盘", "配合团队完成季度目标", "跟进项目进度并及时反馈", "整理数据并输出周报",
        "与相关部门沟通协作", "维护客户关系，提升满意度", "参与流程优化与制度建设", "完成上级交办的其他工作"]
