def pick(seq, w=None):
    return R.choices(seq, weights=w, k=1)[0]


def date():
    d = R.randint(0, 330)
    m, day = 1 + d // 28, 1 + d % 28
    y, m = (2025, min(m, 12))
    r = R.random()
    if r < 0.78:
        return f"{y}-{m:02d}-{day:02d}"
    if r < 0.9:
        return f"{y}/{m}/{day}"
    return f"{y}年{m}月{day}日"


def make_row(i):
    cat = pick(CATS, CATW)
    title = pick(JOBS[cat])
    loc = pick([x for x, _ in LOC], [w for _, w in LOC])
    comp = f"示例公司{i % 97 + 1:02d}（合成）"
    r = R.random()
    reqs = R.sample(REQ, 3)
    if r < 0.45:   # explicit
        k = R.random()
        if k < 0.62:
            a = pick(CAP); line = pick(AGE_EXPLICIT).format(a=a)
        elif k < 0.80:
            lo, hi = pick(RANGES); line = pick(["{lo}-{hi}岁", "{lo}~{hi}周岁", "年龄：{lo}至{hi}岁", "年龄{lo}-{hi}周岁"]).format(lo=lo, hi=hi)
        elif k < 0.88:
            line = f"{R.choice([28, 30, 35])}岁以上，有一定阅历"
        else:
            a = pick(CAP); line = pick(AGE_EXPLICIT).format(a=a)
        if R.random() < 0.28:
            line += "，" + pick(EXC)
        reqs.insert(R.randint(0, 3), line)
        if R.random() < 0.25:
            reqs.append(pick(TRAPS))
    elif r < 0.55:  # uncertain
        reqs.insert(R.randint(0, 3), pick(UNCERTAIN))
    else:           # none; many with experience traps
        if R.random() < 0.35:
            reqs.insert(R.randint(0, 3), pick(TRAPS))
    duties = R.sample(DUTY, 4)
    desc = "岗位职责：\n" + "\n".join(f"{n}、{d}；" for n, d in enumerate(duties, 1)) + "\n任职要求：\n" + \
        "\n".join(f"{n}、{q}；" for n, q in enumerate(reqs, 1)) + f"\n（本条为合成示例数据 #{i:03d}，非真实招聘信息）"
    sal = f"{R.choice([6, 8, 10, 12, 15, 20])}-{R.choice([12, 16, 20, 25, 30])}K"
    return [f"{title}", comp, loc, date(), cat, desc, f"https://example.invalid/demo/{i:03d}", "合成示例数据", sal]


def main():
    rows = [make_row(i) for i in range(1, 293)]
    for j in (10, 55, 120, 200, 250, 270, 280, 285):  # exact duplicate rows (re-posted ads)
        rows.append(list(rows[j]))
    R.shuffle(rows)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["职位名称", "公司", "工作地点", "发布日期", "职位类别", "职位描述", "职位链接", "来源", "薪资"])
        w.writerows(rows)
    (OUT.parent / "README.txt").write_text(
        "demo_ads.csv is SYNTHETIC data generated by scripts/make_demo_data.py (seeded, deterministic).\n"
        "Companies are fictional, URLs are example.invalid, every description ends with a synthetic-data note.\n"
        "It is not real job-ad data and must never be presented as such. Import only with --demo (is_demo=1).\n", encoding="utf-8")
    print(f"wrote {len(rows)} rows to {OUT}")


if __name__ == "__main__":
    main()
