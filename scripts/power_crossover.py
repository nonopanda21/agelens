#!/usr/bin/env python3
"""Power and threshold-success probability for the planned crossover (crossover-rules-v1; docs/EVAL_PLAN.md). Stdlib, seeded.

Model (same family as scripts/power_analysis.py, all assumptions unverified until the pilot):
  each participant has a latent per-task usable probability q ~ Beta(mean p0, within-person correlation rho);
  ad-only tasks (A) use q, AgeLens tasks (B) use min(.999, q + delta); 2 tasks per condition;
  optional carryover c: in the BA sequence (AgeLens first) the later ad-only tasks use q + c (a learned benefit that
  shrinks the measured difference). Sequences are balanced (half AB, half BA).
Per simulated trial: D_i = share(B) - share(A); reported
  power    = P(two-sided paired t p < .05)  (the sign-flip test the analysis uses agrees closely; see --check)
  success  = P(pre-registered threshold met: mean D >= +0.20 AND 95% CI lower bound > 0), CI by t interval for speed
             (the analysis uses a percentile bootstrap; --check compares them).
Usage: python3 scripts/power_crossover.py [--sims 4000] [--check] [--out data/study/power_crossover.md]"""
import argparse, math, random, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from power_analysis import ab, t_two_sided_p  # noqa: E402

SEED, ALPHA, MIN_EFFECT = 20261027, 0.05, 0.20


def t_crit(df):
    lo, hi = 1.0, 20.0  # two-sided 95% critical value by bisection on the p-value
    for _ in range(60):
        mid = (lo + hi) / 2
        if t_two_sided_p(mid, df) > 0.05: lo = mid
        else: hi = mid
    return hi


TCRIT = {}


def trial(rng, n, p0, delta, rho, carry):
    D = []
    for i in range(n):
        q = rng.betavariate(*ab(p0, rho)) if rho > 1e-9 else p0
        ba = i % 2 == 1  # half the sequences put AgeLens first
        qa = min(0.999, q + (carry if ba else 0.0)); qb = min(0.999, q + delta)
        a = sum(rng.random() < qa for _ in range(2)); b = sum(rng.random() < qb for _ in range(2))
        D.append((b - a) / 2)
    m = sum(D) / n; sd = math.sqrt(sum((x - m) ** 2 for x in D) / (n - 1))
    if sd == 0:
        return (m != 0), (m >= MIN_EFFECT and m > 0), D
    se = sd / math.sqrt(n)
    tc = TCRIT.setdefault(n - 1, t_crit(n - 1))
    return t_two_sided_p(m / se, n - 1) < ALPHA, (m >= MIN_EFFECT - 1e-12 and m - tc * se > 0), D


def run(n, p0, delta, rho, carry, sims, seed):
    rng = random.Random("%s|%d|%s|%s|%s|%s" % (seed, n, p0, delta, rho, carry)); pw = sc = 0
    for _ in range(sims):
        a, b, _ = trial(rng, n, p0, delta, rho, carry); pw += a; sc += b
    return pw / sims, sc / sims


def check(sims=300):
    """Compare the t-based shortcuts with the analysis script's sign-flip test and percentile bootstrap."""
    from analyze_study import boot_mean_ci, signflip_p
    rng = random.Random(SEED); agree_p = agree_s = 0
    for _ in range(sims):
        a, b, D = trial(rng, 24, 0.35, 0.25, 0.2, 0.0)
        lo, _ = boot_mean_ci(D, 2000, random.Random(rng.random()))
        m = sum(D) / len(D)
        agree_p += a == (signflip_p(D, 2000, random.Random(rng.random())) < ALPHA)
        agree_s += b == (m >= MIN_EFFECT - 1e-12 and lo > 0)
    return agree_p / sims, agree_s / sims


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--sims", type=int, default=4000); ap.add_argument("--check", action="store_true"); ap.add_argument("--out")
    a = ap.parse_args()
    L = ["# Crossover power (crossover-rules-v1)", "",
         "Generated by `scripts/power_crossover.py --sims %d` (seed %d). Model and assumptions in the script header; **no pilot data exist, so every input is an assumption.** "
         "power = P(paired t p < .05); success = P(pre-registered threshold met: mean D >= +0.20 and 95%% CI lower bound > 0)." % (a.sims, SEED), ""]
    L += ["## Main table (template baseline p0 = .35, within-person correlation rho = .2)", "",
          "| N | true effect | carryover | power | P(threshold met) |", "|---|---|---|---|---|"]
    for n in (16, 24, 32, 48):
        for d in (0.15, 0.25, 0.35):
            for c in (0.0, 0.10):
                pw, sc = run(n, 0.35, d, 0.2, c, a.sims, SEED)
                L.append("| %d | +%.2f | %s | %.2f | %.2f |" % (n, d, "none" if c == 0 else "+%.2f" % c, pw, sc))
    L += ["", "## Robustness at N = 24, effect +.25, no carryover", "", "| p0 | rho | power | P(threshold met) |", "|---|---|---|---|"]
    for p0 in (0.2, 0.35, 0.5):
        for rho in (0.0, 0.2, 0.4):
            pw, sc = run(24, p0, 0.25, rho, 0.0, a.sims, SEED)
            L.append("| %.2f | %.1f | %.2f | %.2f |" % (p0, rho, pw, sc))
    L += ["", "## False success rate (true effect 0)", "", "| N | P(threshold met) |", "|---|---|"]
    for n in (16, 24, 32, 48):
        L.append("| %d | %.3f |" % (n, run(n, 0.35, 0.0, 0.2, 0.0, a.sims, SEED)[1]))
    if a.check:
        p_ag, s_ag = check()
        L += ["", "Check (300 trials, N=24, +.25): t test vs sign-flip same decision %.0f%%; t-interval vs bootstrap threshold decision same %.0f%%." % (100 * p_ag, 100 * s_ag)]
    txt = "\n".join(L) + "\n"
    print(txt)
    if a.out:
        Path(a.out).write_text(txt)


if __name__ == "__main__":
    main()
